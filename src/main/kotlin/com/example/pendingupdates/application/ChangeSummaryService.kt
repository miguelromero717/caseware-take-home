package com.example.pendingupdates.application

import com.example.pendingupdates.domain.PendingStatus
import com.example.pendingupdates.domain.TemplateId
import com.example.pendingupdates.domain.TemplateVersion
import com.example.pendingupdates.ports.ChangeType
import com.example.pendingupdates.ports.DiffEntry
import com.example.pendingupdates.ports.ReleaseNotes
import com.example.pendingupdates.ports.TemplateDiffTool
import java.security.MessageDigest
import java.util.concurrent.ConcurrentHashMap

data class ChangeSummary(
    val templateId: TemplateId,
    val from: TemplateVersion,
    val to: TemplateVersion,
    /** Deterministic, generated by code from the diff. Authoritative. */
    val changeList: List<String>,
    /** Per-version notes, newest last, with previously declined versions flagged. */
    val versionNotes: List<VersionNote>,
) {
    /** Stored in the decision log so we can prove what the user was shown. */
    val hash: String by lazy {
        val text = (changeList + versionNotes.map { "${it.version}:${it.previouslyDeclined}:${it.note}" }).joinToString("\n")
        MessageDigest.getInstance("SHA-256").digest(text.toByteArray()).joinToString("") { "%02x".format(it) }
    }
}

data class VersionNote(val version: TemplateVersion, val previouslyDeclined: Boolean, val note: String?)

/**
 * Turns template diffs into a readable summary. Template data is identical across firms, so the
 * change list for a range is computed once and shared, keyed by (template, from, to).
 * The diff is a net diff: a procedure added in v5 and removed in v6 doesn't appear in v4→v6.
 */
class ChangeSummaryService(
    private val diffTool: TemplateDiffTool,
    private val releaseNotes: ReleaseNotes,
) {
    private data class RangeKey(val templateId: TemplateId, val from: TemplateVersion, val to: TemplateVersion)

    // Skeleton: in-process cache. In production this is a shared cache (e.g. S3 or Redis), since
    // the same range is reused by every firm.
    private val changeLists = ConcurrentHashMap<RangeKey, List<String>>()

    fun summarize(templateId: TemplateId, pending: PendingStatus.Pending): ChangeSummary {
        val key = RangeKey(templateId, pending.diffFrom, pending.diffTo)
        val changeList = changeLists.getOrPut(key) {
            render(diffTool.diff(templateId, pending.diffFrom, pending.diffTo))
        }
        val notes = pending.versions.map {
            VersionNote(it.version, it.previouslyDeclined, releaseNotes.noteFor(templateId, it.version))
        }
        return ChangeSummary(templateId, pending.diffFrom, pending.diffTo, changeList, notes)
    }

    private fun render(entries: List<DiffEntry>): List<String> = entries
        .sortedBy { it.path }
        .map { entry ->
            val verb = when (entry.change) {
                ChangeType.ADDED -> "Added"
                ChangeType.REMOVED -> "Removed"
                ChangeType.MODIFIED -> "Modified"
            }
            "$verb: ${entry.label}"
        }
}
